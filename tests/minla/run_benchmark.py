#!/usr/bin/env python3
"""
run_benchmark.py — BT MinLA Layout Performance Benchmark
=========================================================
Compares btf_tick_tree() execution time between:
  - DFS pre-order layout   (parser default, no optimization)
  - SA-optimized layout    (Fiedler init + SA α=0.995)

Procedure
---------
  For each scenario (DFS, SA):
    1. Generate 5 random BT instances with N=20 nodes.
    2. For each instance:
       a. Generate a C test program implementing action functions
          with 70% BTF_SUCCESS_STATUS / 30% BTF_FAILURE_STATUS.
       b. The program initializes the tree, ticks it 20 times,
          times each tick, and prints the average of the 5 slowest
          tick times (in nanoseconds).
       c. Compile the program against libBTreeFy-Src.
       d. Run it 10 times; record the printed value each time.
    3. Compute the average of the 10 runs per instance.
  Store results in results/dfs_results.csv and results/sa_results.csv.
  Print a side-by-side comparison table.

Working directory: tests/minla/  (run from there or from repo root)

Usage
-----
  cd tests/minla
  python3 run_benchmark.py
"""

import os
import sys
import subprocess
import csv
import re
import statistics
import textwrap

# ── Path setup ────────────────────────────────────────────────────────────────
_HERE      = os.path.dirname(os.path.abspath(__file__))         # tests/minla/
_TESTS_DIR = os.path.dirname(_HERE)                             # tests/
_REPO      = os.path.dirname(_TESTS_DIR)                        # btreefy-repo/
_SCRIPTS   = os.path.join(_REPO, "scripts")
_INCLUDE   = os.path.join(_REPO, "include")
_LIB       = os.path.join(_REPO, "build", "lib", "libBTreeFy-Src.a")
_GEN_SCRIPT = os.path.join(_SCRIPTS, "minla", "gen_random_instances.py")

# ── Parameters ────────────────────────────────────────────────────────────────
N_NODES     = 20
K_INSTANCES = 5
TICKS       = 20       # btf_tick_tree calls per run
TOP_K_SLOW  = 5        # keep the N slowest ticks for averaging
REPETITIONS = 10       # times each compiled binary is executed

RESULTS_DIR = os.path.join(_HERE, "results")
os.makedirs(RESULTS_DIR, exist_ok=True)

# ── C test template ───────────────────────────────────────────────────────────
# Placeholders:
#   {action_impls}  — one function body per leaf action
#   {ticks}         — number of btf_tick_tree calls
#   {top_k}         — number of slowest samples to average

_C_TEMPLATE = textwrap.dedent("""\
    /* Auto-generated by run_benchmark.py — DO NOT EDIT */
    #include <stdio.h>
    #include <stdlib.h>
    #include <time.h>

    #include "btreefy/btreefy.h"
    #include "btreefy/btreefy_objs.h"
    #include "btf_action_functions_generated.h"

    extern struct btf_node nodes[];
    extern size_t          nodes_size;

    /* ── Action implementations (70% SUCCESS / 30% FAILURE) ── */
    {action_impls}

    /* ── Comparison for qsort (descending — slowest first) ── */
    static int cmp_desc(const void *a, const void *b) {{
        long long da = *(const long long *)a;
        long long db = *(const long long *)b;
        return (db > da) - (db < da);
    }}

    int main(void) {{
        srand(42);

        struct btf_tree tree;
        btf_init(&tree, nodes, (uint32_t)nodes_size);

        long long times[{ticks}];

        for (int t = 0; t < {ticks}; t++) {{
            struct timespec t0, t1;
            clock_gettime(CLOCK_MONOTONIC, &t0);
            btf_tick_tree(&tree);
            clock_gettime(CLOCK_MONOTONIC, &t1);
            times[t] = (long long)(t1.tv_sec - t0.tv_sec) * 1000000000LL
                     + (t1.tv_nsec - t0.tv_nsec);
        }}

        /* Sort descending to isolate the {top_k} slowest */
        qsort(times, {ticks}, sizeof(long long), cmp_desc);

        long long sum = 0;
        for (int i = 0; i < {top_k}; i++) {{
            sum += times[i];
        }}
        /* Print average of the {top_k} slowest ticks in nanoseconds */
        printf("%lld\\n", sum / {top_k});

        return 0;
    }}
""")

_ACTION_IMPL = """\
enum btf_node_status {name}(struct btf_tree *tree) {{
    return (rand() % 10 < 7) ? BTF_SUCCESS_STATUS : BTF_FAILURE_STATUS;
}}
"""


# ── Helpers ───────────────────────────────────────────────────────────────────

def _parse_action_names(h_path: str) -> list[str]:
    """Extract function names from btf_action_functions_generated.h."""
    names = []
    with open(h_path) as f:
        for line in f:
            m = re.search(r'btf_node_status\s+(\w+)\s*\(', line)
            if m:
                names.append(m.group(1))
    return names


def _generate_c_test(inst_dir: str) -> str:
    """Write test_bt_minla.c into inst_dir. Returns the file path."""
    h_path    = os.path.join(inst_dir, "btf_action_functions_generated.h")
    names     = _parse_action_names(h_path)
    impls     = "\n".join(_ACTION_IMPL.format(name=n) for n in names)
    c_source  = _C_TEMPLATE.format(
        action_impls = impls,
        ticks        = TICKS,
        top_k        = TOP_K_SLOW,
    )
    c_path = os.path.join(inst_dir, "test_bt_minla.c")
    with open(c_path, "w") as f:
        f.write(c_source)
    return c_path


def _compile(inst_dir: str) -> str:
    """Compile test_bt_minla.c → test_bt_minla binary. Returns binary path."""
    c_file  = os.path.join(inst_dir, "test_bt_minla.c")
    c_nodes = os.path.join(inst_dir, "btf_nodes_generated.c")
    binary  = os.path.join(inst_dir, "test_bt_minla")

    cmd = [
        "gcc", "-O2",
        f"-I{_INCLUDE}",
        c_file, c_nodes, _LIB,
        "-o", binary,
        "-lm",
    ]
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(
            f"Compilation failed in {inst_dir}:\n{result.stderr}"
        )
    return binary


def _run_binary(binary: str) -> int:
    """Run the binary once, return the printed nanosecond value (last line)."""
    result = subprocess.run([binary], capture_output=True, text=True, timeout=10)
    if result.returncode != 0:
        raise RuntimeError(f"Binary failed: {result.stderr}")
    # The library may print debug messages; our value is always the last line
    lines = [l.strip() for l in result.stdout.splitlines() if l.strip()]
    return int(lines[-1])


def _run_instance(inst_dir: str, label: str) -> list[int]:
    """
    Full pipeline for one instance directory:
      generate C → compile → run REPETITIONS times → return list of ns values.
    """
    _generate_c_test(inst_dir)
    binary = _compile(inst_dir)

    readings = []
    for _ in range(REPETITIONS):
        ns = _run_binary(binary)
        readings.append(ns)
    return readings


# ── Scenario runner ───────────────────────────────────────────────────────────

def run_scenario(label: str, optimize: bool, out_csv: str) -> list[dict]:
    inst_root = os.path.join(_HERE, f"instances_{'sa' if optimize else 'dfs'}")

    print(f"\n{'='*60}")
    print(f"Scenario: {label}")
    print(f"Instances dir: {inst_root}")
    print(f"{'='*60}")

    # 1. Generate instances
    gen_cmd = [
        sys.executable, _GEN_SCRIPT,
        "--n", str(N_NODES),
        "--k", str(K_INSTANCES),
        "--output-dir", inst_root,
        "--seed", "0",
    ]
    if optimize:
        gen_cmd.append("--optimize")

    print(f"Generating {K_INSTANCES} instances (n={N_NODES}) …")
    subprocess.run(gen_cmd, check=True)

    # 2. For each instance: generate C, compile, run
    width = len(str(K_INSTANCES - 1))
    rows  = []

    for i in range(K_INSTANCES):
        inst_dir = os.path.join(inst_root, str(i).zfill(width))
        print(f"\n  [instance {i}] {inst_dir}")

        readings = _run_instance(inst_dir, label)
        avg_ns   = statistics.mean(readings)
        std_ns   = statistics.stdev(readings) if len(readings) > 1 else 0.0
        min_ns   = min(readings)
        max_ns   = max(readings)

        print(f"    runs={readings}")
        print(f"    avg={avg_ns:.1f} ns  std={std_ns:.1f}  "
              f"min={min_ns}  max={max_ns}")

        rows.append({
            "instance":    i,
            "scenario":    label,
            "avg_ns":      round(avg_ns, 2),
            "std_ns":      round(std_ns, 2),
            "min_ns":      min_ns,
            "max_ns":      max_ns,
            "readings":    ";".join(str(r) for r in readings),
        })

    # 3. Write CSV
    fieldnames = ["instance", "scenario", "avg_ns", "std_ns", "min_ns", "max_ns", "readings"]
    with open(out_csv, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
    print(f"\n  Results → {out_csv}")
    return rows


# ── Comparison table ──────────────────────────────────────────────────────────

def print_comparison(dfs_rows: list[dict], sa_rows: list[dict]) -> None:
    print(f"\n{'='*70}")
    print("COMPARISON: DFS layout vs SA-optimized layout")
    print(f"  N={N_NODES} nodes · {TICKS} ticks/run · avg of {TOP_K_SLOW} slowest · {REPETITIONS} repetitions")
    print(f"{'='*70}")
    print(f"{'Inst':>5}  {'DFS avg (ns)':>14}  {'SA avg (ns)':>13}  {'Δ (ns)':>10}  {'Δ (%)':>8}")
    print("-" * 70)

    for dfs, sa in zip(dfs_rows, sa_rows):
        delta    = sa["avg_ns"] - dfs["avg_ns"]
        delta_pct = delta / dfs["avg_ns"] * 100 if dfs["avg_ns"] else 0.0
        sign     = "+" if delta > 0 else ""
        print(f"{dfs['instance']:>5}  {dfs['avg_ns']:>14.1f}  {sa['avg_ns']:>13.1f}  "
              f"{sign}{delta:>9.1f}  {sign}{delta_pct:>7.2f}%")

    # Overall averages
    dfs_overall = statistics.mean(r["avg_ns"] for r in dfs_rows)
    sa_overall  = statistics.mean(r["avg_ns"] for r in sa_rows)
    delta_overall = sa_overall - dfs_overall
    delta_pct_overall = delta_overall / dfs_overall * 100

    print("-" * 70)
    sign = "+" if delta_overall > 0 else ""
    print(f"{'mean':>5}  {dfs_overall:>14.1f}  {sa_overall:>13.1f}  "
          f"{sign}{delta_overall:>9.1f}  {sign}{delta_pct_overall:>7.2f}%")
    print(f"{'='*70}")
    print("  Δ < 0 means SA is faster (better cache locality for this workload)")
    print(f"{'='*70}\n")

    # Write comparison CSV
    comp_csv = os.path.join(RESULTS_DIR, "comparison.csv")
    with open(comp_csv, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=[
            "instance", "dfs_avg_ns", "sa_avg_ns", "delta_ns", "delta_pct"
        ])
        writer.writeheader()
        for dfs, sa in zip(dfs_rows, sa_rows):
            d = sa["avg_ns"] - dfs["avg_ns"]
            writer.writerow({
                "instance":   dfs["instance"],
                "dfs_avg_ns": dfs["avg_ns"],
                "sa_avg_ns":  sa["avg_ns"],
                "delta_ns":   round(d, 2),
                "delta_pct":  round(d / dfs["avg_ns"] * 100 if dfs["avg_ns"] else 0.0, 3),
            })
    print(f"  Comparison CSV → {comp_csv}")


# ── Entry point ───────────────────────────────────────────────────────────────

if __name__ == "__main__":
    import time

    # Ensure library is built
    if not os.path.exists(_LIB):
        print(f"Library not found at {_LIB}")
        print("Run ./compile-execute.sh from the repo root first.")
        sys.exit(1)

    t0 = time.perf_counter()

    dfs_rows = run_scenario(
        label   = "DFS",
        optimize= False,
        out_csv = os.path.join(RESULTS_DIR, "dfs_results.csv"),
    )

    sa_rows = run_scenario(
        label   = "SA",
        optimize= True,
        out_csv = os.path.join(RESULTS_DIR, "sa_results.csv"),
    )

    print_comparison(dfs_rows, sa_rows)

    print(f"Total wall time: {time.perf_counter() - t0:.1f}s")
